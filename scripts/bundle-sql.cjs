// Concatenates supabase/migrations/*.sql into one file to paste into the Supabase SQL editor.
// Writes deploy/supabase-all-migrations.sql and the same content to supabase/all.sql (both are referenced in the docs).
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "..", "supabase", "migrations");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out = ["-- lockin. — all migrations in order. Paste into Supabase → SQL Editor → Run.", "-- Generated by `npm run db:bundle`; edit supabase/migrations/*.sql, not this file.", ""];
for (const f of files) out.push(`-- ==== ${f} ====`, fs.readFileSync(path.join(dir, f), "utf8").trim(), "");
for (const target of [["deploy", "supabase-all-migrations.sql"], ["supabase", "all.sql"]]) fs.writeFileSync(path.join(__dirname, "..", ...target), out.join("\n"));
console.log(`deploy/supabase-all-migrations.sql and supabase/all.sql: ${files.length} migrations`);
