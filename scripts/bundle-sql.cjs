// Concatenates supabase/migrations/*.sql into deploy/supabase-all-migrations.sql: one file to paste into the Supabase SQL editor.
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "..", "supabase", "migrations");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const out = ["-- lockin. — all migrations in order. Paste into Supabase → SQL Editor → Run.", "-- Generated by `npm run db:bundle`; edit supabase/migrations/*.sql, not this file.", ""];
for (const f of files) out.push(`-- ==== ${f} ====`, fs.readFileSync(path.join(dir, f), "utf8").trim(), "");
fs.writeFileSync(path.join(__dirname, "..", "deploy", "supabase-all-migrations.sql"), out.join("\n"));
console.log(`deploy/supabase-all-migrations.sql: ${files.length} migrations`);
